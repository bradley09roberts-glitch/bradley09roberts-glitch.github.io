#!/usr/bin/env python3
"""Generate docs/INVENTORY.md from run/inventory.json (written by the server during self-test phase 1 or by
/grandline test inventory) plus the self-test reports (run/selftest-phase1.txt, run/selftest-phase2.txt) and the
client verification report (docs/client-verification.txt, optional).

Status legend (never inflated):
  planned  - designed and listed, no working code yet
  partial  - some working code, but listed pieces are missing or placeholders
  playable - works in game end to end, not covered by an automated check
  tested   - exercised by an automated check on a dedicated server (the check is named in Notes)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN = os.path.join(ROOT, "run")


def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return ""


inv = json.loads(read(os.path.join(RUN, "inventory.json")) or "{}")
if not inv:
    sys.exit("run/inventory.json missing: run self-test phase 1 (GL_SELFTEST=1) or /grandline test inventory")
report = read(os.path.join(RUN, "selftest-phase1.txt")) + "\n" + read(os.path.join(RUN, "selftest-phase2.txt"))
client = read(os.path.join(ROOT, "docs", "client-verification.txt"))
passes = [l for l in report.splitlines() if l.startswith("PASS")]
LANG = {}
lang_dir = os.path.join(ROOT, "src", "main", "lang", "en_us")
for fn in sorted(os.listdir(lang_dir)) if os.path.isdir(lang_dir) else []:
    if fn.endswith(".json"):
        LANG.update(json.loads(read(os.path.join(lang_dir, fn)) or "{}"))


def island_name(i):
    return i.get("name") or LANG.get("island.grandline." + i["id"]) or i["id"]
all_abilities_ok = any(re.match(r"PASS all \d+ abilities execute", l) for l in passes)


def mentioned(token):
    token = token.lower()
    return [l[5:].split(" — ")[0] for l in passes if token in l.lower()]


out = []
w = out.append
w("# Grand Line Odyssey — Inventory")
w("")
w("Generated by `tools/gen_inventory.py` from the live registries and world plan (`run/inventory.json`) and the")
w("latest self-test reports. Do not edit by hand; re-run the self-test and the script.")
w("")
w("| Status | Meaning |")
w("|---|---|")
w("| planned | designed and listed, no working code yet |")
w("| partial | some working code; the Notes column lists what is missing or still a placeholder |")
w("| playable | works in game end to end, but no automated check covers it |")
w("| tested | exercised by an automated check on a dedicated server (named in Notes) |")
w("")


def status_counts(rows):
    c = {}
    for r in rows:
        c[r] = c.get(r, 0) + 1
    return ", ".join(f"{k} {v}" for k, v in sorted(c.items()))


# ---------------- Islands ----------------
islands = inv.get("islands", [])
canon = [i for i in islands if i["canon"]]
orig = [i for i in islands if not i["canon"]]
isl_rows = []


def island_status(i):
    notes = []
    placeholders = [l["id"] for l in i["landmarks"] if not l["implemented"]]
    if placeholders:
        notes.append("placeholder landmark: " + ", ".join(placeholders))
    inhabited = i["settlement"] != "NONE"
    if inhabited and i["npcs"] == 0:
        notes.append("no NPC markers")
    if i["chests"] + i["secrets"] == 0:
        notes.append("no loot/secrets")
    if i.get("error"):
        notes.append("layout error: " + i["error"])
    if i["quests"] == 0 and i["canon"]:
        notes.append("no story quest yet (board jobs only)" if i["boards"] else "no quests yet")
    if not i["canon"] and i.get("plan", "ocean") == "ocean" and not i.get("story"):
        notes.append("no local story")  # every original island should have a generated story (quest/story)
    hits = mentioned(i["id"])
    if not placeholders and not i.get("error") and (not inhabited or i["npcs"] > 0):
        st = "tested" if hits else "playable"
    else:
        st = "partial"
    if hits:
        notes.insert(0, "self-test: " + "; ".join(hits))
    return st, notes


w("## Islands")
w("")
w(f"{len(islands)} islands in the current world plan: {len(canon)} canon/starter at fixed positions, {len(orig)} original")
w("(procedurally generated from themed templates; count configurable). Every island has generated terrain, biome")
w("theme, beaches and resources; columns show what the real builders place (counted by running them).")
w("Sky islands (Skypiea, Weatheria) and Fish-Man Island belong to their own dimensions and are listed separately.")
w("")
w("### Canon and starter islands")
w("")
w("| Island | Sea | Settlement | Buildings | NPC spawns | Chests | Secrets | Landmarks | Story quests | Status | Notes |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for i in sorted(canon, key=lambda i: (i["zone"], i["x"])):
    st, notes = island_status(i)
    isl_rows.append(st)
    lms = ", ".join((l["id"] if l["implemented"] else l["id"] + " (placeholder)") for l in i["landmarks"]) or "—"
    name = island_name(i)
    w(f"| {name} | {i['zone'].lower()} | {i['settlement'].lower()} | {i['buildings']} | {i['npcs']} | {i['chests']} | {i['secrets']} | {lms} | {i['quests']} | {st} | {'; '.join(notes)} |")
w("")
w(f"Canon/starter island status: {status_counts(isl_rows)}.")
w("")
w("### Original islands (generated)")
w("")
orow = []
by_zone = {}
for i in orig:
    st, notes = island_status(i)
    orow.append(st)
    z = by_zone.setdefault(i["zone"], {"n": 0, "settled": 0, "npcs": 0, "chests": 0, "secrets": 0})
    z["n"] += 1
    z["settled"] += i["settlement"] != "NONE"
    z["npcs"] += i["npcs"]
    z["chests"] += i["chests"]
    z["secrets"] += i["secrets"]
    z["stories"] = z.get("stories", 0) + (1 if i.get("story") else 0)
    z["jobs"] = z.get("jobs", 0) + i.get("boardJobs", 0)
w("| Sea zone | Islands | Settled | NPC spawns | Chests | Secrets | Local stories | Board jobs |")
w("|---|---|---|---|---|---|---|---|")
for k, z in sorted(by_zone.items()):
    w(f"| {k.lower()} | {z['n']} | {z['settled']} | {z['npcs']} | {z['chests']} | {z['secrets']} | {z.get('stories', 0)} | {z.get('jobs', 0)} |")
w("")
templates = {}
for i in orig:
    if i.get("story"):
        templates[i["story"]] = templates.get(i["story"], 0) + 1
with_story = sum(1 for i in orig if i.get("story"))
w(f"Original island status: {status_counts(orow)}. {with_story}/{len(orig)} original islands have a local story generated from the")
w("world seed (quest/story, docs/STORY.md, \"Original islands\"): " + ", ".join(f"{LANG.get('story.grandline.tpl.' + t, t)} {n}" for t, n in sorted(templates.items())) + ".")
w("Settled islands' notice boards also offer generated jobs (deliveries, escorts, outlaw hunts, nests or camps, salvage, fish, meals, timber).")
w("")
w("<details><summary>Full list of original islands</summary>")
w("")
w("| Id | Name | Sea | Shape | Theme | Settlement | Buildings | NPC spawns | Chests | Secrets | Story | Status |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|")
for i in sorted(orig, key=lambda i: (i["zone"], i["x"])):
    st, _ = island_status(i)
    story = LANG.get("story.grandline.tpl." + i["story"], i["story"]) if i.get("story") else "—"
    w(f"| {i['id']} | {island_name(i)} | {i['zone'].lower()} | {i['shape'].lower()} | {i['theme'].lower()} | {i['settlement'].lower()} | {i['buildings']} | {i['npcs']} | {i['chests']} | {i['secrets']} | {story} | {st} |")
w("")
w("</details>")
w("")

# ---------------- Races ----------------
w("## Races")
w("")
w("| Race | Canon | Playable | Scale | Race abilities | Status | Notes |")
w("|---|---|---|---|---|---|---|")
role_races = {r["race"] for r in inv.get("roles", [])}
rrows = []
for r in inv.get("races", []):
    notes = []
    hits = mentioned(r["id"])
    if r["playable"]:
        st = "tested" if hits else "playable"
    else:
        st = "playable" if r["id"] in role_races else "partial"
        notes.append("NPC race" + ("" if r["id"] in role_races else ": stats/visuals defined, no NPC role spawns it yet"))
    if hits:
        notes.insert(0, "self-test: " + "; ".join(hits))
    if r["id"] in client:
        notes.append("rendered in client screenshot")
    rrows.append(st)
    w(f"| {r['id']} | {'yes' if r['canon'] else 'original'} | {'yes' if r['playable'] else 'NPC'} | {r['minScale']:.2f}–{r['maxScale']:.2f} | {r['abilities']} | {st} | {'; '.join(notes)} |")
w("")
w(f"Race status: {status_counts(rrows)}.")
w("")

# ---------------- Fruits ----------------
w("## Devil Fruits")
w("")
fr = inv.get("fruits", [])
w(f"{len(fr)} fruits on the roster ({sum(f['canon'] for f in fr)} canon, {sum(not f['canon'] for f in fr)} original). "
  "Only fruits with implemented abilities can spawn in the world. `*` marks awakened-only abilities.")
w("")
w("| Fruit | Type | Canon | Element | Abilities | Status | Notes |")
w("|---|---|---|---|---|---|---|")
frows = []
for f in fr:
    ab = f["abilities"]
    if ab:
        st = "tested" if all_abilities_ok else "playable"
        note = "every ability executed in self-test 'all abilities execute'" if all_abilities_ok else ""
        extra = mentioned("fruit/" + f["id"]) + mentioned(" " + f["id"] + " ")
        if extra:
            note += "; " + "; ".join(sorted(set(extra)))
    else:
        st, note = "planned", "roster entry only (no abilities yet, cannot spawn)"
    frows.append(st)
    w(f"| {f['id']} | {f['type'].lower()} | {'yes' if f['canon'] else 'original'} | {f['element'].lower()} | {', '.join(ab) or '—'} | {st} | {note} |")
w("")
w(f"Fruit status: {status_counts(frows)}.")
w("")

# ---------------- Weapons ----------------
w("## Weapons")
w("")
arts = inv.get("weaponArts", {})
w("| Weapon class | Ranged | Combo length | Weapon arts | Items (id:grade) | Status |")
w("|---|---|---|---|---|---|")
wrows = []
for wc in inv.get("weapons", []):
    n_arts = sum(v for k, v in arts.items() if k == wc["id"] or wc["id"].startswith(k) or k.startswith(wc["id"]))
    st = "tested" if (all_abilities_ok and n_arts) else "playable"
    if not wc["items"]:
        st = "partial"
    wrows.append(st)
    w(f"| {wc['id']} | {'yes' if wc['ranged'] else 'no'} | {wc['chain']} | {n_arts} | {', '.join(wc['items']) or '— (no item yet)'} | {st} |")
w("")
w(f"Weapon status: {status_counts(wrows)}. Weapon-art families: " + ", ".join(f"{k} ({v})" for k, v in sorted(arts.items())) + ".")
w("")

# ---------------- Styles ----------------
w("## Fighting styles")
w("")
w("| Style | Canon | Race-locked | Combo length | Techniques | Status |")
w("|---|---|---|---|---|---|")
srows = []
for s in inv.get("styles", []):
    st = "tested" if (all_abilities_ok and s["techniques"]) else ("playable" if s["chain"] else "planned")
    srows.append(st)
    w(f"| {s['id']} | {'yes' if s['canon'] else 'original'} | {s['race'] or '—'} | {s['chain']} | {', '.join(s['techniques']) or '—'} | {st} |")
w("")
w(f"Style status: {status_counts(srows)}.")
w("")

# ---------------- Ships ----------------
w("## Ships")
w("")
w("| Class | Length × beam | Hull | Speed | Cannons | Masts | Seats | Price (Beli) | Below deck | Status | Notes |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
shrows = []
for s in inv.get("ships", []):
    hits = mentioned(s["id"])
    st = "tested" if hits else "playable"
    shrows.append(st)
    w(f"| {s['id']} | {s['length']} × {s['beam']} | {s['hull']} | {s['speed']:.2f} | {s['cannons']} | {s['masts']} | {s['seats']} | {s['price']:,} | {'yes' if s['interior'] else 'no'} | {st} | {'; '.join(hits)} |")
w("")
w(f"Ship status: {status_counts(shrows)}.")
w("")

# ---------------- Characters ----------------
w("## Characters")
w("")
generated_people = [n for n in inv.get("notables", []) if n.get("generated")]
named = [n for n in inv.get("notables", []) if not n.get("generated")]
if named:
    w("### Named original characters")
    w("")
    w(f"{len(named)} original characters (no canon characters appear). Each spawns once per world on its home island; "
      "killed characters stay dead and their fruit returns to the world. Recruitable ones can join your crew.")
    w("")
    w("| Character | Title | Group | Faction | Home | Tier | Fruit | Style | Crew | Status | Notes |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for n in sorted(named, key=lambda n: (n["group"], -n["tier"])):
        hits = mentioned(n["id"])
        st = "tested" if hits else "playable"
        name = LANG.get(n["nameKey"], n["id"])
        title = LANG.get(n["titleKey"], "")
        crew = n["crewRole"] if n["recruitable"] else ""
        w(f"| {name} | {title} | {n['group']} | {n['faction']} | {n['island']} | {n['tier']} | {n['fruit'] or '—'} | {n['style']} | {crew} | {st} | {'; '.join(hits)} |")
    w("")
if generated_people:
    w(f"Plus {len(generated_people)} people generated from the world seed for the island stories and the notice boards (givers, "
      "witnesses, villains, outlaws, couriers), named by sea; they spawn and die like the cast above.")
    w("")
w("### NPC roles (archetypes)")
w("")
w("| Role | Faction | Base tier | Race | Style | Behaviour | Fruit chance | Haki chance | Status |")
w("|---|---|---|---|---|---|---|---|---|")
for r in inv.get("roles", []):
    hits = mentioned(r["id"])
    st = "tested" if hits else "playable"
    w(f"| {r['id']} | {r['faction'].lower()} | {r['tier']} | {r['race']} | {r['style']} | {r['hostility'].lower()} | {r['fruitChance']:.0%} | {r['hakiChance']:.0%} | {st} |")
w("")

# ---------------- Quests ----------------
w("## Quests")
w("")
qs = inv.get("quests", [])
arcs = {}
for q in qs:
    arcs.setdefault(q["arc"] or "misc", []).append(q)
w("| Arc | Quests | Islands |")
w("|---|---|---|")
for a, l in sorted(arcs.items()):
    isl = sorted({q['island'] for q in l if q['island']})
    if any(q.get("generated") for q in l):  # generated arcs span the whole world: count, don't list
        w(f"| {a} | {len(l)} | {len(isl)} islands (generated from the seed) |")
        continue
    w(f"| {a} | {len(l)} | {', '.join(isl) or 'any'} |")
w("")

with open(os.path.join(ROOT, "docs", "INVENTORY.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote docs/INVENTORY.md:", len(islands), "islands,", len(fr), "fruits")
