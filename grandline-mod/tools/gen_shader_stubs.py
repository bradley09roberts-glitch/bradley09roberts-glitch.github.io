#!/usr/bin/env python3
"""Writes the small per-dimension program files of the Grand Line Shaders pack.

Every dimension folder (world0, world-1, world1, sky, deep, interior; mapped in shaders/dimension.properties) holds one
stub per program: it sets the dimension and program codes and includes the shared body from shaders/program/.
Run after adding a program or a dimension:  python3 tools/gen_shader_stubs.py
"""
from pathlib import Path

SHADERS = Path(__file__).resolve().parent.parent / "shaderpack" / "GrandLineShaders" / "shaders"

# folder -> (DIM code, has a shadow pass)
DIMENSIONS = {
    "world0": (0, True),     # minecraft:overworld (+ fallback for unknown dimensions)
    "world-1": (1, False),   # minecraft:the_nether
    "world1": (2, False),    # minecraft:the_end
    "sky": (3, True),        # grandline:sky
    "deep": (4, False),      # grandline:deep_sea
    "interior": (5, False),  # grandline:ship_interiors
}

# program -> (vertex body, fragment body, PROG_ID code)
PROGRAMS = {
    "shadow": ("shadow.vsh", "shadow.fsh", 1),
    "gbuffers_basic": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 20),
    "gbuffers_textured": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 21),
    "gbuffers_textured_lit": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 22),
    "gbuffers_weather": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 23),
    "gbuffers_beaconbeam": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 24),
    "gbuffers_spidereyes": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 25),
    "gbuffers_armor_glint": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 26),
    "gbuffers_lightning": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 27),
    "gbuffers_clouds": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 30),
    "gbuffers_skybasic": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 40),
    "gbuffers_skytextured": ("gbuffers_forward.vsh", "gbuffers_forward.fsh", 41),
    "gbuffers_damagedblock": ("gbuffers_forward.vsh", "gbuffers_damaged.fsh", 60),
    "gbuffers_terrain": ("gbuffers_deferred.vsh", "gbuffers_deferred.fsh", 10),
    "gbuffers_entities": ("gbuffers_deferred.vsh", "gbuffers_deferred.fsh", 11),
    "gbuffers_block": ("gbuffers_deferred.vsh", "gbuffers_deferred.fsh", 12),
    "gbuffers_hand": ("gbuffers_deferred.vsh", "gbuffers_deferred.fsh", 13),
    "gbuffers_water": ("gbuffers_water.vsh", "gbuffers_water.fsh", 50),
    "gbuffers_hand_water": ("gbuffers_water.vsh", "gbuffers_water.fsh", 51),
    "deferred": ("fullscreen.vsh", "deferred.fsh", 0),
    "composite": ("fullscreen.vsh", "composite.fsh", 0),
    "composite1": ("fullscreen.vsh", "composite1.fsh", 0),
    "final": ("fullscreen.vsh", "final.fsh", 0),
}

TEMPLATE = """#version 330 compatibility
// generated by tools/gen_shader_stubs.py: {folder}/{name}
#define DIM {dim}
#define PROG_ID {prog}
#include "/program/{body}"
"""


def main():
    written = 0
    for folder, (dim, shadows) in DIMENSIONS.items():
        out = SHADERS / folder
        out.mkdir(parents=True, exist_ok=True)
        for old in out.glob("*.[vf]sh"):
            old.unlink()
        for program, (vsh, fsh, code) in PROGRAMS.items():
            if program == "shadow" and not shadows:
                continue
            for ext, body in (("vsh", vsh), ("fsh", fsh)):
                name = f"{program}.{ext}"
                (out / name).write_text(TEMPLATE.format(folder=folder, name=name, dim=dim, prog=code, body=body))
                written += 1
    print(f"wrote {written} program stubs into {SHADERS}")


if __name__ == "__main__":
    main()
