#!/usr/bin/env python3
"""Writes docs/ASSET_LIST.md: every file the building, texture and shader overhaul added or changed, grouped by kind,
with the generator that owns it. Compares the working tree's HEAD against the last commit before the overhaul.

    python3 -I tools/gen_asset_list.py [base commit]      (default: e9baef5, the 0.1.0 release state)
"""
import collections
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = sys.argv[1] if len(sys.argv) > 1 else 'e9baef5'

# (path prefix, group title, who makes it)
GROUPS = [
    ('src/main/resources/assets/grandline/textures/block/', 'Block textures (16×16 PNG)', 'painted by `tools/assetgen/arch_textures.py`'),
    ('src/main/resources/assets/grandline/blockstates/', 'Block states', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/assets/grandline/models/block/', 'Block models', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/assets/grandline/models/item/', 'Item models', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/data/grandline/loot_table/blocks/', 'Block loot tables', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/data/grandline/recipe/', 'Recipes (crafting, stonecutting)', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/data/minecraft/tags/', 'Vanilla tags (mineable, stairs, slabs, walls, ...)', '`tools/gen_assets.py`'),
    ('src/main/lang/', 'English names (source fragment)', '`tools/assetgen/arch_blocks.py`'),
    ('src/main/resources/assets/grandline/lang/', 'Language files', '`tools/gen_assets.py`'),
    ('src/main/java/', 'Java source', 'hand-written (ArchBlocks.java is generated)'),
    ('shaderpack/', 'Shader pack source (Iris format)', 'hand-written GLSL'),
    ('dist/', 'Release files', 'Gradle build and `tools/pack_shaders.py`'),
    ('tools/', 'Tools', 'hand-written'),
    ('docs/', 'Documentation, audit, renders and captures', 'see each file'),
    ('', 'Other', ''),
]


def git(*args):
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def main():
    rows = []
    for line in git('diff', '--name-status', '--relative', BASE, 'HEAD', '--', '.').splitlines():
        st, path = line.split('\t')[0], line.split('\t')[-1]
        rows.append((st[0], path))
    grouped = collections.OrderedDict((g[1], []) for g in GROUPS)
    for st, path in sorted(rows, key=lambda r: r[1]):
        for prefix, title, _ in GROUPS:
            if path.startswith(prefix):
                grouped[title].append((st, path))
                break
    owner = {g[1]: g[2] for g in GROUPS}
    word = {'A': 'added', 'M': 'changed', 'D': 'removed', 'R': 'renamed'}
    out = ['# Asset list for the building, texture and shader overhaul\n',
           f'Every file added or changed since `{BASE}` (the 0.1.0 state), grouped by kind. This file is generated by '
           '`tools/gen_asset_list.py`.\n',
           'Every texture and model is original work made for this mod. The textures are painted by code and the models '
           'are written by the block spec. No file is copied from Minecraft or from another pack. The shader pack is '
           'original GLSL written against the Iris shader pipeline.\n',
           '| kind | added | changed | made by |', '|---|---|---|---|']
    for title, items in grouped.items():
        if items:
            c = collections.Counter(s for s, _ in items)
            out.append(f'| {title} | {c.get("A", 0)} | {c.get("M", 0) + c.get("R", 0)} | {owner[title]} |')
    out.append(f'\n**Total:** {len(rows)} files.\n')
    for title, items in grouped.items():
        if not items:
            continue
        out.append(f'## {title}\n')
        if title.startswith('Block textures'):
            out.append('| texture | status |')
            out.append('|---|---|')
            for st, path in items:
                out.append(f'| `{os.path.basename(path)}` | {word.get(st, st)} |')
        else:
            for st, path in items:
                out.append(f'- `{path}` ({word.get(st, st)})')
        out.append('')
    with open(os.path.join(ROOT, 'docs', 'ASSET_LIST.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('docs/ASSET_LIST.md', len(rows), 'files')


if __name__ == '__main__':
    main()
