    // --- Selenite Sentinel -------------------------------------------------------------------------------------

    public static class SeleniteSentinelModel extends EntityModel<SentinelState> {
        private final ModelPart head;
        private final ModelPart rightArm;
        private final ModelPart leftArm;
        private final ModelPart rightLeg;
        private final ModelPart leftLeg;

        public SeleniteSentinelModel(ModelPart root) {
            super(root);
            this.head = root.getChild("head");
            this.rightArm = root.getChild("right_arm");
            this.leftArm = root.getChild("left_arm");
            this.rightLeg = root.getChild("right_leg");
            this.leftLeg = root.getChild("left_leg");
        }

        @Override
        public void setupAnim(SentinelState state) {
            super.setupAnim(state);
            float pos = state.walkAnimationPos;
            float speed = Math.min(1.0F, state.walkAnimationSpeed);
            this.head.yRot = state.yRot * DEG;
            this.head.xRot = state.xRot * DEG;
            this.rightLeg.xRot = Mth.cos(pos * 0.6F) * 0.8F * speed;
            this.leftLeg.xRot = -Mth.cos(pos * 0.6F) * 0.8F * speed;
            this.rightArm.xRot = -Mth.cos(pos * 0.6F) * 0.5F * speed;
            this.leftArm.xRot = Mth.cos(pos * 0.6F) * 0.5F * speed;
            if (state.charge > 0) {
                float c = Math.min(1.0F, state.charge / 20.0F);
                this.rightArm.xRot = -2.4F * c;
                this.leftArm.xRot = -2.4F * c;
                this.rightArm.zRot = 0.3F * c;
                this.leftArm.zRot = -0.3F * c;
            }
            if (state.attackTime > 0.0F) {
                float swing = Mth.sin(state.attackTime * Mth.PI);
                this.rightArm.xRot = -2.0F + swing * 2.4F;
                this.leftArm.xRot = -2.0F + swing * 2.4F;
            }
        }
    }

