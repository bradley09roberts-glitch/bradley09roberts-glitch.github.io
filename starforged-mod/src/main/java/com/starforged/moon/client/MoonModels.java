    // --- Regolith Skimmer --------------------------------------------------------------------------------------

    public static class RegolithSkimmerModel extends EntityModel<SkimmerState> {
        private final ModelPart body;
        private final ModelPart jaw;
        private final ModelPart rightFin;
        private final ModelPart leftFin;
        private final ModelPart tail1;
        private final ModelPart tail2;
        private final ModelPart dorsal;

        public RegolithSkimmerModel(ModelPart root) {
            super(root);
            this.body = root.getChild("body");
            this.jaw = ModLayers.path(root, "body/head/jaw");
            this.rightFin = this.body.getChild("right_fin");
            this.leftFin = this.body.getChild("left_fin");
            this.tail1 = this.body.getChild("tail1");
            this.tail2 = this.tail1.getChild("tail2");
            this.dorsal = root.getChild("dorsal");
        }

        @Override
        public void setupAnim(SkimmerState state) {
            super.setupAnim(state);
            float age = state.ageInTicks;
            float swim = state.walkAnimationPos;
            float speed = Math.min(1.0F, state.walkAnimationSpeed * 1.5F);
            this.body.visible = state.emerge > 0.05F;
            float sway = Mth.sin(swim * 0.7F) * 0.35F * speed + Mth.sin(age * 0.1F) * 0.08F;
            this.body.yRot = sway * 0.3F;
            this.tail1.yRot = -sway;
            this.tail2.yRot = -sway * 1.4F;
            float flap = Mth.sin(age * 0.3F) * 0.25F;
            this.rightFin.zRot = flap;
            this.leftFin.zRot = -flap;
            this.dorsal.zRot = sway * 0.4F;
            this.jaw.xRot = state.emerge > 0.5F ? 0.5F + Mth.sin(age * 0.6F) * 0.3F : 0.05F;
            this.body.xRot = -state.emerge * 0.35F;
        }
    }

