    public static class AshenKnightModel extends EntityModel<KnightState> {
        private final ModelPart head;
        private final ModelPart body;
        private final ModelPart rightArm;
        private final ModelPart leftArm;
        private final ModelPart rightLeg;
        private final ModelPart leftLeg;

        public AshenKnightModel(ModelPart root) {
            super(root);
            this.head = root.getChild("head");
            this.body = root.getChild("body");
            this.rightArm = root.getChild("right_arm");
            this.leftArm = root.getChild("left_arm");
            this.rightLeg = root.getChild("right_leg");
            this.leftLeg = root.getChild("left_leg");
        }

        @Override
        public void setupAnim(KnightState state) {
            super.setupAnim(state);
            float pos = state.walkAnimationPos;
            float speed = state.walkAnimationSpeed;
            this.head.yRot = state.yRot * DEG;
            this.head.xRot = state.xRot * DEG;
            this.rightLeg.xRot = Mth.cos(pos * 0.6662F) * 1.2F * speed;
            this.leftLeg.xRot = Mth.cos(pos * 0.6662F + Mth.PI) * 1.2F * speed;
            this.rightArm.xRot = Mth.cos(pos * 0.6662F + Mth.PI) * 0.6F * speed - 0.3F;
            this.leftArm.xRot = Mth.cos(pos * 0.6662F) * 0.4F * speed - 0.2F;
            if (state.guarding) {
                this.leftArm.xRot = -0.85F;
                this.leftArm.yRot = 0.45F;
            }
            if (state.cleaveTicks > 0.0F) {
                float t = state.cleaveTicks;
                if (t < AshenKnightEntity.CLEAVE_WINDUP) {
                    float raise = ease(t / (AshenKnightEntity.CLEAVE_WINDUP - 2.0F));
                    this.rightArm.xRot = -2.9F * raise;
                    this.rightArm.yRot = 0.5F * raise;
                } else {
                    float swing = ease((t - AshenKnightEntity.CLEAVE_WINDUP) / 4.0F);
                    this.rightArm.xRot = -2.9F + 3.4F * swing;
                    this.rightArm.yRot = 0.5F - 1.4F * swing;
                    this.body.yRot = -0.4F * swing;
                }
            } else if (state.attackTime > 0.0F) {
                float swing = Mth.sin(state.attackTime * Mth.PI);
                this.rightArm.xRot = -1.8F + swing * 1.6F;
            }
        }
    }

