    public static class SolarPylonModel extends Model<PylonState> {
        private final ModelPart top;

        public SolarPylonModel(ModelPart root) {
            super(root, RenderTypes::entityCutout);
            this.top = root.getChild("top");
        }

        @Override
        public void setupAnim(PylonState state) {
            super.setupAnim(state);
            float age = state.ageInTicks;
            this.top.yRot = age * 0.08F;
            this.top.y += Mth.sin(age * 0.12F) * 1.2F;
        }
    }
