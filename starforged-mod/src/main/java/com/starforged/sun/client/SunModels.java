    public static class SolarPhoenixModel extends EntityModel<PhoenixState> {
        private final ModelPart body;
        private final ModelPart neck;
        private final ModelPart head;
        private final ModelPart rightWing;
        private final ModelPart rightTip;
        private final ModelPart leftWing;
        private final ModelPart leftTip;
        private final ModelPart tail;

        public SolarPhoenixModel(ModelPart root) {
            super(root);
            this.body = root.getChild("body");
            this.neck = this.body.getChild("neck");
            this.head = this.neck.getChild("head");
            this.rightWing = this.body.getChild("right_wing");
            this.rightTip = this.rightWing.getChild("right_wing_tip");
            this.leftWing = this.body.getChild("left_wing");
            this.leftTip = this.leftWing.getChild("left_wing_tip");
            this.tail = this.body.getChild("tail");
        }

        @Override
        public void setupAnim(PhoenixState state) {
            super.setupAnim(state);
            float age = state.ageInTicks;
            float rate = state.ridden ? 0.45F : 0.3F;
            float t = age * rate;
            float amp = 0.75F;
            this.rightWing.zRot = Mth.sin(t) * amp;
            this.rightTip.zRot = Mth.sin(t - 0.8F) * amp * 0.7F;
            this.leftWing.zRot = -Mth.sin(t) * amp;
            this.leftTip.zRot = -Mth.sin(t - 0.8F) * amp * 0.7F;
            this.body.y += Mth.cos(t) * 1.2F;
            this.body.xRot = state.xRot * DEG * 0.5F;
            this.neck.xRot = -0.6F + Mth.sin(age * 0.1F) * 0.05F;
            this.head.xRot = 0.6F;
            this.head.yRot = state.yRot * DEG * 0.5F;
            this.tail.xRot = 0.25F + Mth.sin(t + 1.0F) * 0.12F;
            this.tail.yRot = Mth.sin(age * 0.06F) * 0.15F;
        }
    }

    // --- Sun Warden --------------------------------------------------------------------------------------------

    public static class SunWardenModel extends EntityModel<WardenState> {
        private final ModelPart waist;
        private final ModelPart torso;
        private final ModelPart head;
        private final ModelPart halo;
        private final ModelPart rightArm;
        private final ModelPart leftArm;
        private final ModelPart rightLeg;
        private final ModelPart leftLeg;
        private final ModelPart sword;

        public SunWardenModel(ModelPart root) {
            super(root);
            this.waist = root.getChild("waist");
            this.torso = this.waist.getChild("torso");
            this.head = this.torso.getChild("head");
            this.halo = this.torso.getChild("halo");
            this.rightArm = root.getChild("right_arm");
            this.leftArm = root.getChild("left_arm");
            this.rightLeg = root.getChild("right_leg");
            this.leftLeg = root.getChild("left_leg");
            this.sword = ModLayers.path(this.rightArm, "right_gauntlet/sword");
        }

        private void arms(float rx, float lx, float rz, float lz) {
            this.rightArm.xRot = rx;
            this.leftArm.xRot = lx;
            this.rightArm.zRot = rz;
            this.leftArm.zRot = lz;
        }

        private void lower(float amount) {
            this.waist.y += amount;
            this.rightArm.y += amount;
            this.leftArm.y += amount;
        }

        @Override
        public void setupAnim(WardenState state) {
            super.setupAnim(state);
            float pos = state.walkAnimationPos;
            float speed = Math.min(1.0F, state.walkAnimationSpeed);
            float age = state.ageInTicks;
            this.head.yRot = state.yRot * DEG * 0.8F;
            this.head.xRot = state.xRot * DEG * 0.6F;
            this.halo.zRot = age * (state.phase == SunWardenEntity.PHASE_SUPERNOVA ? 0.12F : 0.025F);
            float pulse = 1.0F + Mth.sin(age * 0.15F) * 0.04F;
            this.halo.xScale = pulse;
            this.halo.yScale = pulse;
            this.rightLeg.xRot = Mth.cos(pos * 0.5F) * 0.7F * speed;
            this.leftLeg.xRot = Mth.cos(pos * 0.5F + Mth.PI) * 0.7F * speed;
            this.arms(Mth.cos(pos * 0.5F + Mth.PI) * 0.4F * speed - 0.15F, Mth.cos(pos * 0.5F) * 0.4F * speed, 0.08F, -0.08F);
            this.torso.zRot = Mth.cos(pos * 0.5F) * 0.04F * speed;
            this.waist.y += Math.abs(Mth.sin(pos * 0.5F)) * -1.2F * speed;

            float t = state.attackTicks;
            switch (state.attack) {
                case SunWardenEntity.ATTACK_SUNFALL -> {
                    float up = ease(t / 14.0F);
                    this.arms(-2.9F * up, -0.4F * up, 0.1F, -0.5F * up);
                    this.head.xRot -= 0.5F * up;
                }
                case SunWardenEntity.ATTACK_BEAM -> {
                    float c = ease(t / 20.0F);
                    this.arms(-0.6F * c, -0.6F * c, 0.8F * c, -0.8F * c);
                    this.torso.xRot = -0.18F * c;
                }
                case SunWardenEntity.ATTACK_PILLARS -> {
                    float phase = (t % 20.0F) / 20.0F;
                    float raise = phase < 0.5F ? ease(phase * 2.0F) : 1.0F - ease((phase - 0.5F) * 4.0F);
                    this.arms(-2.4F * raise, -2.4F * raise, 0.0F, 0.0F);
                    this.torso.xRot = 0.25F * (1.0F - raise);
                }
                case SunWardenEntity.ATTACK_SLAM -> {
                    if (t < 8) {
                        float crouch = ease(t / 8.0F);
                        this.lower(3.0F * crouch);
                        this.arms(-0.8F * crouch, -0.8F * crouch, 0.0F, 0.0F);
                    } else if (t < 60) {
                        this.arms(-3.0F, -3.0F, 0.2F, -0.2F);
                    } else {
                        float s = ease((t - 60.0F) / 5.0F);
                        this.arms(-3.0F + 2.2F * s, -3.0F + 2.2F * s, 0.0F, 0.0F);
                        this.lower(3.0F * (1.0F - s));
                        this.torso.xRot = 0.35F * (1.0F - s);
                    }
                }
                case SunWardenEntity.ATTACK_SWEEP -> {
                    if (t < SunWardenEntity.SWEEP_HIT) {
                        float wind = ease(t / (SunWardenEntity.SWEEP_HIT - 2.0F));
                        this.rightArm.xRot = -1.6F * wind;
                        this.rightArm.yRot = 1.1F * wind;
                        this.torso.yRot = 0.4F * wind;
                    } else {
                        float s = ease((t - SunWardenEntity.SWEEP_HIT) / 4.0F);
                        this.rightArm.xRot = -1.6F;
                        this.rightArm.yRot = 1.1F - 2.4F * s;
                        this.torso.yRot = 0.4F - 0.9F * s;
                    }
                }
                case SunWardenEntity.ATTACK_SUMMON -> {
                    float up = ease(t / 15.0F);
                    this.arms(-2.0F * up, -2.0F * up, 0.9F * up, -0.9F * up);
                    this.head.xRot -= 0.4F * up;
                }
                case SunWardenEntity.ATTACK_CORONA -> {
                    if (t < 25) {
                        float c = ease(t / 20.0F);
                        this.arms(-1.4F * c, -1.4F * c, -0.6F * c, 0.6F * c);
                    } else {
                        float s = ease((t - 25.0F) / 4.0F);
                        this.arms(-1.4F, -1.4F, -0.6F + 1.8F * s, 0.6F - 1.8F * s);
                    }
                }
                default -> {
                }
            }
            if (state.phase == SunWardenEntity.PHASE_SUPERNOVA || state.phase == SunWardenEntity.PHASE_STUNNED) {
                // Kneels with the blade planted.
                this.lower(6.0F);
                this.rightLeg.xRot = -1.5F;
                this.rightLeg.z -= 3.0F;
                this.leftLeg.xRot = 0.0F;
                this.leftLeg.y += 2.0F;
                this.arms(-0.9F, -0.4F, 0.0F, 0.0F);
                this.sword.xRot = -0.2F;
                this.torso.xRot = state.phase == SunWardenEntity.PHASE_STUNNED ? 0.45F : 0.1F;
                this.head.xRot = state.phase == SunWardenEntity.PHASE_STUNNED ? 0.5F : -0.3F;
            }
            if (state.phase == SunWardenEntity.PHASE_RISING) {
                float reach = 1.0F - ease(state.rise / (float) SunWardenEntity.RISE_TICKS);
                this.arms(-2.8F + 1.0F * reach, -2.8F + 1.0F * reach, 0.3F, -0.3F);
                this.head.xRot = -0.4F;
            }
            if (state.dying) {
                this.lower(6.0F);
                this.rightLeg.xRot = -1.5F;
                this.rightLeg.z -= 3.0F;
                this.leftLeg.y += 2.0F;
                this.arms(-0.3F, -0.3F, 0.5F, -0.5F);
                this.head.xRot = -0.8F + Mth.sin(age * 2.0F) * 0.05F;
                this.torso.xRot = -0.3F;
            }
        }
    }

