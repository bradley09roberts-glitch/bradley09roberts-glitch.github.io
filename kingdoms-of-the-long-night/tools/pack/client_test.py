#!/usr/bin/env python3
"""Headless CLIENT smoke test of a preset (Linux; Python 3 stdlib + Java 21 + Xvfb + Mesa).

This is the only automated check client-only mods (Sodium, Iris, shaders, Distant Horizons,
Entity Culling, ImmediatelyFast, AmbientSounds, maps, EMI, ...) get. It renders with Mesa's
software rasteriser (llvmpipe), so frame rates say NOTHING about real hardware; it answers
"does the client load all mods, apply all mixins, load resources, compile the shader pack and
render a modded world without errors?".

Steps: install the NeoForge client (installer --installClient), download vanilla libraries and
assets (sound files skipped), build the instance from the manifest (client-side files, sha512
verified) + overrides (+ our longnight jar if built), optionally copy a world generated by
server_test.py into saves/ and quick-play into it, run ~N seconds under Xvfb, take screenshots,
then scan logs.

Usage:
    python3 tools/pack/client_test.py --preset rich [--world DIR_OF_SERVER_WORLD] [--seconds 240]
        [--workdir DIR] [--xmx 6G] [--with-longnight auto|yes|no]
        [--mrpack dist/KingdomsOfTheLongNight-0.1.0-rich.mrpack]   (install exactly like a launcher)
Exit code 0 = PASS.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import time
import urllib.request
import uuid
import zipfile
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import packlib  # noqa: E402
import server_test  # noqa: E402  (reuse the installer download helper)

PISTON = "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json"
RESOURCES = "https://resources.download.minecraft.net"

CLIENT_FATAL = [
    (r"Missing or unsupported mandatory dependencies|Mod loading has failed|ModLoadingException", "mod loading failed"),
    (r"Mixin apply (for mod \S+ )?failed|MixinApplyError|MixinTransformerError|InvalidMixinException|InjectionError", "mixin failure"),
    (r"This crash report has been saved to|---- Minecraft Crash Report ----", "crash"),
    (r"Failed to (compile|link) (shader|program)|Shader compilation failed|Error compiling shader", "shader compile error"),
    (r"Registry loading errors|Error loading registry data|Feature order cycle", "registry/worldgen error"),
    (r"Exception in server tick loop|Encountered an unexpected exception", "integrated server crash"),
]
CLIENT_BENIGN = [
    r"Failed to (open|initialize) OpenAL|OpenAL|Sound engine|audio device|Error starting SoundSystem",
    r"Failed to fetch user properties|Failed to verify authentication|AuthenticationUnavailable|profile public key|Couldn't (load|find) skin",
    r"Missing sound for event|Unable to play unknown soundEvent|Missing sound|sounds\.json",
    r"Realms|realms",
    r"Telemetry|telemetry|YggdrasilUserApiService|Failed to fetch Realms|minecraft\.net|api\.minecraftservices|session ?server",
    r"Failed to load properties from file",
]


def x_click(display, x, y):
    """Left-click at (x, y) on an X display via the XTEST extension (libX11 + libXtst through ctypes)."""
    import ctypes
    try:
        x11 = ctypes.cdll.LoadLibrary("libX11.so.6")
        xtst = ctypes.cdll.LoadLibrary("libXtst.so.6")
    except OSError:
        return False
    x11.XOpenDisplay.restype = ctypes.c_void_p
    x11.XOpenDisplay.argtypes = [ctypes.c_char_p]
    x11.XFlush.argtypes = [ctypes.c_void_p]
    x11.XCloseDisplay.argtypes = [ctypes.c_void_p]
    xtst.XTestFakeMotionEvent.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_ulong]
    xtst.XTestFakeButtonEvent.argtypes = [ctypes.c_void_p, ctypes.c_uint, ctypes.c_int, ctypes.c_ulong]
    d = x11.XOpenDisplay(display.encode())
    if not d:
        return False
    xtst.XTestFakeMotionEvent(d, -1, int(x), int(y), 0)
    x11.XFlush(d)
    time.sleep(0.3)
    xtst.XTestFakeButtonEvent(d, 1, 1, 0)
    x11.XFlush(d)
    time.sleep(0.15)
    xtst.XTestFakeButtonEvent(d, 1, 0, 0)
    x11.XFlush(d)
    x11.XCloseDisplay(d)
    return True


def get(url, dest=None, sha1=None):
    req = urllib.request.Request(url, headers={"User-Agent": packlib.UA})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                data = r.read()
            break
        except Exception:  # noqa: BLE001
            if attempt == 3:
                raise
            time.sleep(2 * (attempt + 1))
    if sha1 and hashlib.sha1(data).hexdigest() != sha1:
        raise SystemExit(f"sha1 mismatch for {url}")
    if dest:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest + ".part", "wb") as fh:
            fh.write(data)
        os.replace(dest + ".part", dest)
    return data


def rules_ok(rules):
    if not rules:
        return True
    allowed = False
    for r in rules:
        if r.get("features"):
            continue  # ignore feature-gated entries (demo, custom resolution, quick play...)
        os_ok = True
        if "os" in r:
            name = r["os"].get("name")
            os_ok = name in (None, "linux") and r["os"].get("arch") in (None, "x86_64", "amd64")
        if os_ok:
            allowed = r["action"] == "allow"
    return allowed


def install_client(neo, install_dir, cache):
    """Install NeoForge client + vanilla libs + assets into install_dir (a launcher-like root)."""
    os.makedirs(install_dir, exist_ok=True)
    prof = os.path.join(install_dir, "launcher_profiles.json")
    if not os.path.exists(prof):
        with open(prof, "w") as fh:
            json.dump({"profiles": {}}, fh)
    vid = f"neoforge-{neo}"
    vjson = os.path.join(install_dir, "versions", vid, f"{vid}.json")
    if not os.path.exists(vjson):
        inst = os.path.join(cache, "neoforge", f"neoforge-{neo}-installer.jar")
        if not os.path.exists(inst):
            server_test.http_get(f"https://maven.neoforged.net/releases/net/neoforged/neoforge/{neo}/"
                                 f"neoforge-{neo}-installer.jar", inst)
        log = os.path.join(install_dir, "installer-client.log")
        with open(log, "w") as fh:
            rc = subprocess.call(["java", "-jar", inst, "--installClient", install_dir], cwd=install_dir,
                                 stdout=fh, stderr=subprocess.STDOUT)
        if rc != 0:
            raise SystemExit(f"client installer failed rc={rc}, see {log}")
    neo_json = json.load(open(vjson))
    mc = neo_json["inheritsFrom"]
    mc_json_path = os.path.join(install_dir, "versions", mc, f"{mc}.json")
    if not os.path.exists(mc_json_path):
        man = json.loads(get(PISTON))
        url = next(v["url"] for v in man["versions"] if v["id"] == mc)
        get(url, mc_json_path)
    mc_json = json.load(open(mc_json_path))
    client_jar = os.path.join(install_dir, "versions", mc, f"{mc}.jar")
    if not os.path.exists(client_jar):
        d = mc_json["downloads"]["client"]
        get(d["url"], client_jar, d["sha1"])
    # vanilla + neoforge libraries
    jobs = []
    for lib in mc_json["libraries"] + neo_json["libraries"]:
        if not rules_ok(lib.get("rules")):
            continue
        art = lib.get("downloads", {}).get("artifact")
        if art and art.get("url"):
            p = os.path.join(install_dir, "libraries", art["path"])
            if not os.path.exists(p):
                jobs.append((art["url"], p, art.get("sha1")))
    # assets (skip the large sound/music files; sounds.json itself is kept)
    ai = mc_json["assetIndex"]
    idx_path = os.path.join(install_dir, "assets", "indexes", f"{ai['id']}.json")
    if not os.path.exists(idx_path):
        get(ai["url"], idx_path, ai["sha1"])
    objs = json.load(open(idx_path))["objects"]
    for name, o in objs.items():
        if name.startswith(("minecraft/sounds/", "minecraft/music/")) or name.endswith(".ogg"):
            continue
        h = o["hash"]
        p = os.path.join(install_dir, "assets", "objects", h[:2], h)
        if not os.path.exists(p):
            jobs.append((f"{RESOURCES}/{h[:2]}/{h}", p, h))
    if jobs:
        print(f"downloading {len(jobs)} vanilla libraries/assets ...")
        with ThreadPoolExecutor(8) as ex:
            list(ex.map(lambda j: get(*j), jobs))
    return neo_json, mc_json, ai["id"]


def build_command(install_dir, game_dir, neo_json, mc_json, asset_index, xmx, quickplay):
    lib_dir = os.path.join(install_dir, "libraries")
    cp, seen = [], set()
    for lib in neo_json["libraries"] + mc_json["libraries"]:  # neoforge entries win
        if not rules_ok(lib.get("rules")):
            continue
        art = lib.get("downloads", {}).get("artifact")
        if not art:
            continue
        g, a = lib["name"].split(":")[0:2]
        key = (g, a, lib["name"].split(":")[3] if lib["name"].count(":") >= 3 else "")
        if key in seen:
            continue
        seen.add(key)
        cp.append(os.path.join(lib_dir, art["path"]))
    # NB: the vanilla versions/<mc>/<mc>.jar must NOT be on the classpath for NeoForge (it would be a second
    # module exporting net.minecraft.*); NeoForge locates the patched game through its own libraries.
    natives = os.path.join(game_dir, "natives")
    os.makedirs(natives, exist_ok=True)
    subs = {
        "${natives_directory}": natives, "${launcher_name}": "kotln-client-test", "${launcher_version}": "1",
        "${classpath}": os.pathsep.join(cp), "${library_directory}": lib_dir, "${classpath_separator}": os.pathsep,
        "${version_name}": neo_json["id"], "${auth_player_name}": "KotLNTester", "${game_directory}": game_dir,
        "${assets_root}": os.path.join(install_dir, "assets"), "${assets_index_name}": asset_index,
        "${auth_uuid}": str(uuid.uuid3(uuid.NAMESPACE_OID, "OfflinePlayer:KotLNTester")).replace("-", ""),
        "${auth_access_token}": "0", "${clientid}": "0", "${auth_xuid}": "0", "${user_type}": "legacy",
        "${version_type}": "release",
    }

    def expand(args):
        out = []
        for a in args:
            if isinstance(a, dict):
                if not rules_ok(a.get("rules")) or any(r.get("features") for r in a.get("rules", [])):
                    continue
                vals = a["value"] if isinstance(a["value"], list) else [a["value"]]
            else:
                vals = [a]
            for v in vals:
                for k, s in subs.items():
                    v = v.replace(k, s)
                out.append(v)
        return out

    jvm = [f"-Xmx{xmx}", "-Xms2G"] + expand(mc_json["arguments"]["jvm"]) + expand(neo_json["arguments"]["jvm"])
    game = expand(mc_json["arguments"]["game"]) + expand(neo_json["arguments"]["game"])
    game += ["--width", "1280", "--height", "720"]
    if quickplay:
        game += ["--quickPlaySingleplayer", quickplay]
    return ["java"] + jvm + [neo_json["mainClass"]] + game


def scan(log_path, crash_dir):
    findings = []
    if os.path.exists(log_path):
        for line in open(log_path, errors="replace"):
            if any(re.search(b, line) for b in CLIENT_BENIGN):
                continue
            for rx, what in CLIENT_FATAL:
                if re.search(rx, line):
                    findings.append(("FATAL", what, line.strip()[:400]))
                    break
            else:
                if re.search(r"/(ERROR|FATAL)\]", line):
                    findings.append(("ERROR", "error line", line.strip()[:400]))
                elif re.search(r"/WARN\]", line):
                    findings.append(("WARN", "warn", line.strip()[:300]))
    else:
        findings.append(("FATAL", "no client log", log_path))
    if os.path.isdir(crash_dir):
        for f in os.listdir(crash_dir):
            findings.append(("FATAL", "crash report", os.path.join(crash_dir, f)))
    return findings


def _safe_rel(path):
    norm = os.path.normpath(path)
    if os.path.isabs(norm) or norm.startswith("..") or "\\" in path:
        raise SystemExit(f"unsafe path in mrpack: {path}")
    return norm


def install_from_mrpack(mrpack, man, game_dir, cache):
    """Install an instance the way a launcher does: read modrinth.index.json, download every
    client file from its URL, verify sha1+sha512+size, extract overrides/ and client-overrides/."""
    with zipfile.ZipFile(mrpack) as z:
        idx = json.loads(z.read("modrinth.index.json"))
        if idx.get("formatVersion") != 1 or idx.get("game") != "minecraft":
            raise SystemExit("not a formatVersion 1 minecraft mrpack")
        deps = idx.get("dependencies", {})
        want = {"minecraft": man["pack"]["minecraft"], man["pack"]["loader"]: man["pack"]["loader_version"]}
        if deps != want:
            raise SystemExit(f"mrpack dependencies {deps} != {want}")
        files = []
        for f in idx["files"]:
            if f.get("env", {}).get("client") == "unsupported":
                continue
            rel = _safe_rel(f["path"])
            entry = {"filename": os.path.basename(rel), "url": f["downloads"][0], "sha1": f["hashes"]["sha1"],
                     "sha512": f["hashes"]["sha512"], "size": f["fileSize"], "path": rel}
            dest = os.path.join(game_dir, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copy2(packlib.download(entry, cache), dest)
            files.append(entry)
        for name in sorted(z.namelist()):
            for prefix in ("overrides/", "client-overrides/"):
                if name.startswith(prefix) and not name.endswith("/"):
                    rel = _safe_rel(name[len(prefix):])
                    dest = os.path.join(game_dir, rel)
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    with open(dest, "wb") as fh:
                        fh.write(z.read(name))
    print(f"installed from {os.path.basename(mrpack)}: {len(files)} downloaded files (hash-verified) + overrides")
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=packlib.MANIFEST)
    ap.add_argument("--preset", default="performance")
    ap.add_argument("--workdir", default=os.path.join(packlib.DEFAULT_CACHE, "client-test"))
    ap.add_argument("--cache", default=packlib.DEFAULT_CACHE)
    ap.add_argument("--world", help="world folder to copy into saves/ and quick-play (e.g. a server_test world)")
    ap.add_argument("--seconds", type=int, default=240, help="seconds to stay in-game after joining")
    ap.add_argument("--load-timeout", type=int, default=1200)
    ap.add_argument("--xmx", default="6G")
    ap.add_argument("--display", default=":77")
    ap.add_argument("--with-longnight", choices=["auto", "yes", "no"], default="auto")
    ap.add_argument("--mrpack", help="build the instance from this built .mrpack exactly like a launcher "
                    "(end-to-end check of the distributable) instead of from the manifest")
    args = ap.parse_args()

    man = packlib.load_manifest(args.manifest)
    neo = man["pack"]["loader_version"]
    install_dir = os.path.abspath(os.path.join(args.workdir, "install"))
    neo_json, mc_json, asset_index = install_client(neo, install_dir, args.cache)

    game_dir = os.path.abspath(os.path.join(args.workdir, args.preset))
    for d in ("mods", "config", "logs", "crash-reports", "saves", "shaderpacks", "screenshots",
              "resourcepacks", "defaultconfigs"):
        shutil.rmtree(os.path.join(game_dir, d), ignore_errors=True)
    for f in ("options.txt",):
        if os.path.exists(os.path.join(game_dir, f)):
            os.remove(os.path.join(game_dir, f))
    os.makedirs(game_dir, exist_ok=True)
    if args.mrpack:
        files, ln = install_from_mrpack(args.mrpack, man, game_dir, args.cache), None
    else:
        files = packlib.preset_files(man, args.preset, "client")
        for f in files:
            dest = os.path.join(game_dir, f["path"])
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copy2(packlib.download(f, args.cache), dest)
        # all overrides (config, options.txt, ...) exactly as the .mrpack would lay them out
        packlib.write_overrides(man, args.preset, game_dir)
        ln = None if args.with_longnight == "no" else packlib.find_longnight_jar()
        if ln:
            shutil.copy2(ln, os.path.join(game_dir, "mods", os.path.basename(ln)))
        elif args.with_longnight == "yes":
            raise SystemExit("FAIL: --with-longnight yes but no longnight jar built")
    quick = None
    if args.world:
        quick = "kotln-client-test"
        shutil.copytree(args.world, os.path.join(game_dir, "saves", quick))
        for junk in ("session.lock",):
            p = os.path.join(game_dir, "saves", quick, junk)
            if os.path.exists(p):
                os.remove(p)
    print(f"instance {game_dir}: {len(files)} files" + (f" + {os.path.basename(ln)}" if ln else ""))

    xvfb = subprocess.Popen(["Xvfb", args.display, "-screen", "0", "1280x720x24", "-nolisten", "tcp"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(2)
    env = dict(os.environ, DISPLAY=args.display, LIBGL_ALWAYS_SOFTWARE="1", GALLIUM_DRIVER="llvmpipe",
               MESA_GL_VERSION_OVERRIDE="4.6", MESA_GLSL_VERSION_OVERRIDE="460", ALSOFT_DRIVERS="null")
    cmd = build_command(install_dir, game_dir, neo_json, mc_json, asset_index, args.xmx, quick)
    with open(os.path.join(game_dir, "launch-command.txt"), "w") as fh:
        fh.write(" ".join(c if " " not in c else repr(c) for c in cmd) + "\n")
    t0 = time.monotonic()
    out = open(os.path.join(game_dir, "client-stdout.log"), "w")
    proc = subprocess.Popen(cmd, cwd=game_dir, env=env, stdout=out, stderr=subprocess.STDOUT)
    log = os.path.join(game_dir, "logs", "latest.log")
    marks = {}
    shots = []
    joined_at = None
    clicks, last_click = 0, -1e9
    try:
        while time.monotonic() - t0 < args.load_timeout + args.seconds:
            time.sleep(5)
            if proc.poll() is not None:
                break
            text = open(log, errors="replace").read() if os.path.exists(log) else ""
            el = time.monotonic() - t0
            for key, rx in (("resources_loaded", r"Created: \d+x\d+x\d+ minecraft:textures/atlas/blocks\.png-atlas"),
                            ("title_screen", r"Game took [\d.]+ seconds to start|Sound engine started"),
                            ("integrated_server", r"Starting integrated minecraft server"),
                            ("joined_world", r"joined the game|logged in with entity id")):
                if key not in marks and re.search(rx, text):
                    marks[key] = round(el, 1)
                    print(f"  {el:6.1f}s {key}")
            if "resources_loaded" in marks and "title_shot" not in marks and el - marks["resources_loaded"] > 20:
                marks["title_shot"] = el
                p = os.path.join(game_dir, f"shot-{int(el)}s.png")
                subprocess.call(["import", "-display", args.display, "-window", "root", p],
                                stderr=subprocess.DEVNULL)
                shots.append(p)
            # Worlds whose dimension data comes from datapacks (Tectonic/Terralith) trigger vanilla's one-time
            # "Worlds using Experimental Settings are not supported" screen; click "I know what I'm doing!"
            # (right-hand button; 1280x720 window, auto GUI scale 3).
            if (quick and "title_screen" in marks and "integrated_server" not in marks
                    and el - marks["title_screen"] > 20 and clicks < 3 and el - last_click > 20):
                p = os.path.join(game_dir, f"shot-{int(el)}s-before-confirm.png")
                subprocess.call(["import", "-display", args.display, "-window", "root", p], stderr=subprocess.DEVNULL)
                shots.append(p)
                x_click(args.display, 880, 464)
                clicks += 1
                last_click = el
                print(f"  {el:6.1f}s clicked 'I know what I'm doing!' on the experimental-settings screen")
            if "joined_world" in marks and joined_at is None:
                joined_at = time.monotonic()
            if joined_at is not None:
                inside = time.monotonic() - joined_at
                if len(shots) < 6 and inside > 30 * (len(shots)):
                    p = os.path.join(game_dir, f"shot-{int(el)}s.png")
                    subprocess.call(["import", "-display", args.display, "-window", "root", p],
                                    stderr=subprocess.DEVNULL)
                    shots.append(p)
                if inside >= args.seconds:
                    break
            if not quick and "resources_loaded" in marks and el - marks["resources_loaded"] > args.seconds:
                break
    finally:
        alive = proc.poll() is None
        if alive:
            proc.send_signal(signal.SIGTERM)
            try:
                proc.wait(60)
            except subprocess.TimeoutExpired:
                proc.kill()
        xvfb.terminate()
    total = time.monotonic() - t0
    findings = scan(log, os.path.join(game_dir, "crash-reports"))
    fatal = [f for f in findings if f[0] == "FATAL"]
    errors = [f for f in findings if f[0] == "ERROR"]
    warns = [f for f in findings if f[0] == "WARN"]
    reached = "resources_loaded" in marks and (not quick or "joined_world" in marks)
    marks["experimental_screen_clicks"] = clicks
    passed = reached and alive and not fatal
    summary = {"preset": args.preset, "result": "PASS" if passed else "FAIL", "milestones_s": marks,
               "alive_until_stopped": alive, "total_s": round(total, 1), "fatal": fatal,
               "error_lines": [e[2] for e in errors], "warn_count": len(warns), "screenshots": shots,
               "log": log, "longnight_jar": ln, "files": len(files)}
    with open(os.path.join(game_dir, "client_test_summary.json"), "w") as fh:
        json.dump(summary, fh, indent=2)
    print("=" * 72)
    print(f" CLIENT TEST {summary['result']}  preset={args.preset}  (software GL; FPS meaningless)")
    print(f" milestones: {marks}; process alive until stopped: {alive}")
    print(f" findings: {len(fatal)} fatal, {len(errors)} ERROR lines, {len(warns)} WARN lines")
    for kind, what, line in fatal[:20]:
        print(f"   [{kind}] {what}: {line}")
    for kind, what, line in errors[:25]:
        print(f"   [{kind}] {line}")
    print(f" screenshots: {shots}")
    print(f" log: {log}")
    print("=" * 72)
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
