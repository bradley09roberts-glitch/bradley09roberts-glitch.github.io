#!/usr/bin/env python3
"""Generate modpack/MODS.md from modpack/manifest.json (Python 3 stdlib only).

Run after resolve_manifest.py so the table never drifts from what the .mrpack files reference.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import packlib  # noqa: E402

CATEGORY_ORDER = ["performance", "atmosphere", "worldgen", "worldgen-structures", "building", "food",
                  "magic", "qol", "visual", "library"]
CATEGORY_TITLE = {
    "performance": "Performance", "atmosphere": "Atmosphere", "worldgen": "World generation",
    "worldgen-structures": "Exploration structures", "building": "Building & decor", "food": "Food & farming",
    "magic": "Magic", "qol": "Quality of life", "visual": "Visual (rich preset)", "library": "Libraries",
}
LICENSE_SHORT = {
    "LicenseRef-All-Rights-Reserved": "ARR (modpack use permitted via Modrinth)",
    "LicenseRef-Custom": "Custom",
}


def side(f):
    s = f["env"]["server"]
    if s == "unsupported":
        return "client"
    if s == "optional":
        return "client + server (optional)"
    return "client + server"


def esc(t):
    return (t or "").replace("|", "\\|").replace("\n", " ")


def main():
    m = packlib.load_manifest()
    files = m["files"]
    out = []
    w = out.append
    w("# Kingdoms of the Long Night - mod list")
    w("")
    w(f"Generated by `tools/pack/gen_mods_md.py` from `modpack/manifest.json` (resolved {m['resolved_at']} "
      f"from the Modrinth API). Minecraft **{m['pack']['minecraft']}**, NeoForge **{m['pack']['loader_version']}**.")
    w("Do not edit by hand: change `modpack/selection.json`, run `resolve_manifest.py`, then this script.")
    w("")
    for pr, cfg in m["presets"].items():
        n = [f for f in files if pr in f["presets"]]
        mods = [f for f in n if f["project_type"] == "mod"]
        w(f"- **{cfg['title']}** (`{pr}`): {len(mods)} mods"
          + (f" + {len(n) - len(mods)} shader pack" if len(n) > len(mods) else "")
          + f", {sum(f['size'] for f in n) / 1048576:.0f} MiB download. {cfg['description']}")
    w("- Plus the `longnight` core mod jar from `mod/build/libs/` when it exists at build time (in `overrides/mods/`).")
    w("")
    w("Side: *client* = client-only (never installed on a dedicated server); *client + server* = needed on both "
      "(singleplayer always runs both). Every file is downloaded from cdn.modrinth.com by the launcher; no "
      "third-party file is redistributed in the .mrpack.")
    w("")
    w("**Credits / licences**: every row links to the official Modrinth page of the project (also the credit "
      "link required by e.g. Xaero's and Complementary licences when the pack is shared outside Modrinth). "
      "The rich preset enables **Complementary Shaders - Reimagined** by EminGT/Complementary Development "
      "(https://www.complementary.dev/) by default, unmodified.")
    w("")
    cats = sorted({f["category"] for f in files}, key=lambda c: CATEGORY_ORDER.index(c) if c in CATEGORY_ORDER else 99)
    for c in cats:
        w(f"## {CATEGORY_TITLE.get(c, c)}")
        w("")
        w("| Mod | Version | Channel | Licence | Side | Presets | Why it is in the pack |")
        w("|---|---|---|---|---|---|---|")
        for f in sorted((x for x in files if x["category"] == c), key=lambda x: x["title"].lower()):
            pin = " (pinned)" if f.get("pinned") else ""
            why = esc(f["reason"])
            if f.get("pin_reason"):
                why += f" *Pin: {esc(f['pin_reason'])}*"
            lic = LICENSE_SHORT.get(f["license"], f["license"].replace("LicenseRef-", ""))
            presets = ", ".join(f["presets"])
            w(f"| [{esc(f['title'])}]({f['homepage']}) | `{f['version_number']}`{pin} | {f['version_type']} | "
              f"{lic} | {side(f)} | {presets} | {why} |")
        w("")
    w("## Considered and rejected")
    w("")
    w("| Candidate | Why not |")
    w("|---|---|")
    for r in m.get("rejected", []):
        name = f"[{r['name']}](https://modrinth.com/mod/{r['slug']})" if r.get("slug") else r["name"]
        w(f"| {name} | {esc(r['reason'])} |")
    w("")
    if m.get("warnings"):
        w("## Resolver warnings")
        w("")
        for x in m["warnings"]:
            w(f"- {esc(x)}")
        w("")
    w("## Exact files (for auditing)")
    w("")
    w("<details><summary>Modrinth project/version ids, file names and sha512 prefixes</summary>")
    w("")
    w("| slug | project id | version id | file | size | sha1 | sha512 (first 16) |")
    w("|---|---|---|---|---|---|---|")
    for f in files:
        w(f"| {f['slug']} | `{f['project_id']}` | `{f['version_id']}` | `{f['filename']}` | {f['size']} | "
          f"`{f['sha1']}` | `{f['sha512'][:16]}` |")
    w("")
    w("</details>")
    w("")
    path = os.path.join(packlib.MODPACK, "MODS.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote", os.path.relpath(path, packlib.ROOT))


if __name__ == "__main__":
    main()
