def _apply(g, faces, part, ov):
    for face, rows in faces.items():
        g.face_ascii(part, face, rows, ov=ov)


def make_hair(hid):
    st = STYLES[hid]
    g = LevelSkin()
    base = {k: v for k, v in st.items() if k in ('top', 'front', 'right', 'back', 'bottom')}
    _apply(g, base, 'head', False)
    if 'left' in st:
        g.face_ascii('head', 'left', st['left'])
    else:
        g.mirror_head()
    ov = st.get('ov', {})
    if ov:
        _apply(g, {k: v for k, v in ov.items() if k != 'left'}, 'head', True)
        if 'right' in ov:
            g.mirror_head(ov=True)
        if 'left' in ov:
            g.face_ascii('head', 'left', ov['left'], ov=True)
    jk = st.get('jacket', {})
    for face, rows in jk.items():
        g.face_ascii('body', face, rows, ov=True)
        if face == 'right':
            g.face_ascii('body', 'left', [r[::-1] for r in rows], ov=True)
    return g
